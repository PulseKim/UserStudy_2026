#!/usr/bin/env python3
"""Filter exported data, compute summaries, and create publication-quality plots."""
import argparse, json
from datetime import datetime, timezone
from pathlib import Path
import matplotlib.pyplot as plt
import pandas as pd

ROOT=Path(__file__).parent; OUT=ROOT/"data"/"processed"; FIG=ROOT/"figures"
plt.rcParams.update({"figure.dpi":150,"savefig.dpi":300,"axes.spines.top":False,"axes.spines.right":False})
# Forced choice (A/B). "Neither" only appears for data collected before the No-preference option was removed.
RESPONSE_ORDER=["Pure KIMODO","Moa-KIMODO","Neither"]
RESPONSE_COLORS=["#635BFF","#00A6A6","#E879A9"]
PLOT_BACKGROUND="#F3F0FA"
def prefs(df, group):
    result=df.groupby([group,"preferred_method"]).size().rename("count").reset_index()
    result["proportion"]=result["count"]/result.groupby(group)["count"].transform("sum")
    return result
def plot(table,index,title,path,stacked=False):
    if table.empty: return
    p=table.pivot(index=index,columns="preferred_method",values="proportion").fillna(0)
    method_order=[method for method in ["Pure KIMODO","Moa-KIMODO"] if method in p.columns]
    if method_order: p=p.reindex(columns=method_order)
    if index == "trial_type": p=p.reindex([kind for kind in ["sequence","kinematic"] if kind in p.index])
    ax=p.plot.bar(stacked=stacked,figsize=(max(6,len(p)*.55),4.5),width=.8)
    ax.set(title=title,xlabel="",ylabel="Proportion preferred",ylim=(0,1)); ax.legend(title="Preferred method",frameon=False)
    plt.tight_layout(); plt.savefig(path); plt.close()

def load_data(snapshot, sessions_csv=None):
    if snapshot.suffix.lower() == ".json":
        data=json.loads(snapshot.read_text(encoding="utf-8"))
        return pd.DataFrame(data["study_sessions"]), pd.json_normalize(data["trial_responses"],sep=".")
    if snapshot.suffix.lower() == ".csv":
        if sessions_csv is None:
            raise SystemExit("CSV analysis requires --sessions-csv study_sessions_rows.csv")
        return pd.read_csv(sessions_csv), pd.read_csv(snapshot)
    raise SystemExit("The input must be a JSON snapshot or trial responses CSV file.")

def additional_summaries(study):
    """Optional summaries retained for future use but not generated by default."""
    return {
        "preference_overall": prefs(study.assign(overall="Overall"),"overall"),
        "preference_by_trial": prefs(study,"trial_id"),
        "trial_exposure": study.groupby("trial_id").size().rename("observations").reset_index(),
        "left_right_balance": pd.concat([
            study.left_method.value_counts().rename("left"),
            study.right_method.value_counts().rename("right")
        ],axis=1).fillna(0),
        "response_time_summary": study.response_time_ms.describe(percentiles=[.25,.5,.75,.95])
    }

def response_summary(study, trial_type):
    subset=study[study.trial_type.eq(trial_type)]
    choices=subset.preferred_method.replace({
        "method1":"Pure KIMODO",
        "method2":"Moa-KIMODO",
        "none":"Neither"
    })
    counts=choices.value_counts().reindex(RESPONSE_ORDER,fill_value=0)
    if counts.get("Neither",0)==0:
        counts=counts.drop("Neither")
    total=int(counts.sum())
    percentages=counts.div(total).mul(100) if total else counts.astype(float)
    return pd.DataFrame({"response":list(counts.index),"count":counts.values,"percentage":percentages.values})

def response_plot(summary, trial_type, path, show_title=False):
    fig,ax=plt.subplots(figsize=(6.4,4.6))
    bars=ax.bar(summary.response,summary.percentage,color=RESPONSE_COLORS[:len(summary)],width=.62)
    if show_title:
        ax.set_title(f"Type: {trial_type.capitalize()}",fontsize=17,fontweight="bold",pad=16)
    ax.set_xlabel("")
    ax.set_ylabel("Preference (%)",fontsize=15,labelpad=10)
    ax.set_ylim(0,100)
    ax.grid(axis="y",color="#D8D2E8",linewidth=.9)
    ax.set_axisbelow(True)
    ax.tick_params(axis="x",labelsize=13,pad=8)
    ax.tick_params(axis="y",labelsize=13)
    for bar,value in zip(bars,summary.percentage):
        ax.text(bar.get_x()+bar.get_width()/2,value+2,f"{value:.1f}%",ha="center",va="bottom",fontsize=10,fontweight="bold")
    fig.patch.set_facecolor(PLOT_BACKGROUND); ax.set_facecolor(PLOT_BACKGROUND)
    fig.tight_layout(); fig.savefig(path,bbox_inches="tight",facecolor=PLOT_BACKGROUND); plt.close(fig)

def main():
    ap=argparse.ArgumentParser(); ap.add_argument("snapshot",type=Path,help="Combined JSON snapshot or trial_responses CSV")
    ap.add_argument("--sessions-csv",type=Path,help="study_sessions CSV; required when snapshot is CSV")
    ap.add_argument("--include-test",action="store_true",help="Include rows tagged as test sessions")
    ap.add_argument("--show-title",action="store_true",help="Show the trial type as the plot title"); args=ap.parse_args()
    sessions,responses=load_data(args.snapshot,args.sessions_csv)
    if "is_test" in sessions and not args.include_test: sessions=sessions[~sessions.is_test.fillna(False)]
    sessions=sessions[sessions.completion_status.eq("complete")]
    total_checks=pd.to_numeric(sessions.number_of_attention_checks,errors="coerce").fillna(0)
    correct_checks=pd.to_numeric(sessions.number_of_attention_checks_correct,errors="coerce").fillna(0)
    passed_all_checks=total_checks.gt(0) & correct_checks.eq(total_checks)
    attention=passed_all_checks.value_counts().rename_axis("passed").rename("participants")
    total_comprehension=pd.to_numeric(sessions.number_of_comprehension_checks,errors="coerce").fillna(0)
    correct_comprehension=pd.to_numeric(sessions.number_of_comprehension_checks_correct,errors="coerce").fillna(0)
    passed_comprehension=total_comprehension.gt(0) & correct_comprehension.eq(total_comprehension)
    comprehension=passed_comprehension.value_counts().rename_axis("passed").rename("participants")
    total_participants=len(sessions)
    eligible=sessions[passed_all_checks & passed_comprehension]
    responses=responses[responses.participant_id.isin(eligible.participant_id)].copy()
    is_comprehension=responses["is_comprehension_check"] if "is_comprehension_check" in responses else pd.Series(False,index=responses.index)
    study=responses[~responses.is_attention_check.fillna(False) & ~is_comprehension.fillna(False)].copy()
    OUT.mkdir(parents=True,exist_ok=True); FIG.mkdir(parents=True,exist_ok=True)
    timestamp=datetime.now(timezone.utc).strftime("%m%d%H%M")
    attention.to_csv(OUT/f"attention_summary_{timestamp}.csv")
    comprehension.to_csv(OUT/f"comprehension_summary_{timestamp}.csv")
    for trial_type in ["sequence","kinematic"]:
        summary=response_summary(study,trial_type)
        summary.to_csv(OUT/f"{trial_type}_{timestamp}.csv",index=False)
        response_plot(summary,trial_type,FIG/f"{trial_type}_{timestamp}.png",args.show_title)
    print(f"Eligible participants: {len(eligible)} of {total_participants}.")
if __name__ == "__main__": main()
